/**
 * Compute nutrition for a specific quantity.
 * @param {object} food  — entry from FOOD_DB
 * @param {number} grams — weight in grams
 * @returns {{ cal, protein, carbs, fat, fiber }}
 */
export function computeNutrition(food, grams) {
  const ratio = grams / 100;
  return {
    cal:     Math.round(food.per100g.cal     * ratio * 10) / 10,
    protein: Math.round(food.per100g.protein * ratio * 10) / 10,
    carbs:   Math.round(food.per100g.carbs   * ratio * 10) / 10,
    fat:     Math.round(food.per100g.fat     * ratio * 10) / 10,
    fiber:   Math.round(food.per100g.fiber   * ratio * 10) / 10,
  };
}

/** Get foods filtered by category */
export function getFoodsByCategory(category) {
  if (!category || category === 'all') return FOOD_DB;
  return FOOD_DB.filter(f => f.category === category);
}

/** Search foods by name (case-insensitive) */
export function searchFoods(query) {
  const q = query.toLowerCase().trim();
  if (!q) return FOOD_DB;
  return FOOD_DB.filter(f => f.name.toLowerCase().includes(q));
}

/** Get a food by id */
export function getFoodById(id) {
  return FOOD_DB.find(f => f.id === id) ?? null;
}

